# Checks of the scalar arguments of landscapes, rivers, evolution, speciation and drift_test()

test_that("landscapes check their scalar arguments", {
  expect_error(landscape_implicit(1), "`n_sites`")
  expect_error(landscape_implicit(c(5, 6)), "`n_sites`")
  expect_error(landscape_implicit(5, env_range = c(10, 0)), "`env_range`")
  expect_error(landscape_implicit(5, env_range = c(0, Inf)), "`env_range`")
  expect_error(landscape_grid(side = NA), "`side`")
  expect_error(landscape_grid(side = 3, env_bandwidth = 0), "`env_bandwidth`")
  expect_error(landscape_grid(side = 3, disp_scale = Inf), "`disp_scale`")
  expect_error(landscape_grid(side = 3, torus = NA), "`torus`")
  expect_error(landscape_grid(side = 3, n_axes = 1.5), "`n_axes`")
  xy <- cbind(1:3, 1:3)
  expect_error(landscape_points(xy, env = 1:3, disp_scale = "a"), "`disp_scale`")
  expect_error(landscape_points(xy, env = 1:3, disp_scale = 1, lonlat = "no"), "`lonlat`")
  expect_error(landscape_points(xy, env = c(1, NA, 3), disp_scale = 1), "`env`")
  expect_error(landscape_points(cbind(1:3), env = 1:3, disp_scale = 1), "`coords`")
  expect_error(landscape_matrix(matrix(-1, 3, 3), env = 1:3), "`dispersal`")
  expect_error(landscape_matrix(matrix(1, 3, 3), env = 1:2), "`env`")
  expect_error(landscape_matrix(matrix(1, 3, 3), env = 1:3, coords = cbind(1:2, 1:2)),
               "`coords`")
  expect_error(landscape_matrix(matrix(1, 3, 3), env = 1:3, dist = diag(2)), "`dist`")
  d <- as.matrix(dist(1:4))
  expect_error(dispersal_kernel(d, scale = c(1, 2)), "`scale`")
  expect_error(dispersal_kernel(d, scale = NaN), "`scale`")
  expect_error(dispersal_kernel(1:4, scale = 1), "`dist`")
})


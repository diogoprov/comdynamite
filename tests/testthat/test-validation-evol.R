test_that("river networks and their environments check their arguments", {
  expect_error(river_network(1), "`n_sites`")
  expect_error(river_network(10, branching = 2), "`branching`")
  expect_error(river_network(10, reach_length = 0), "`reach_length`")
  expect_error(river_network(10, fixed_length = NA), "`fixed_length`")
  expect_error(river_network(10, max_branches = 1), "`max_branches`")
  set.seed(1)
  net <- river_network(8)
  expect_error(landscape_river(list(1)), "`network`")
  expect_error(landscape_river(net, scale_down = 0), "`scale_down`")
  expect_error(landscape_river(net, scale_up = NA), "`scale_up`")
  expect_error(landscape_river(net, overland = 1.5), "`overland`")
  expect_error(landscape_river(net, overland_scale = -1), "`overland_scale`")
  expect_error(landscape_river(net, env_range = 1), "`env_range`")
  expect_error(landscape_river(net, env = 1:3), "`env`")
  expect_error(landscape_river(transform(net, x = NA)), "`x` and `y`")
  # an infinite scale upstream is free movement upstream
  expect_s3_class(landscape_river(net, scale_up = Inf), "mc_landscape")
  land <- landscape_river(net)
  expect_error(river_covariance(land, nugget = -1), "`nugget`")
  expect_error(env_river(land, n_steps = 0, nugget = 1), "`n_steps`")
  expect_error(env_river(land, temporal_scale = -1, nugget = 1), "`temporal_scale`")
  expect_error(env_river(land, mean = 1:2, nugget = 1), "`mean`")
  expect_error(river_floods(land, 10, 5, probability = 2), "`probability`")
  expect_error(river_floods(land, 10, 5, size_effect = Inf), "`size_effect`")
  expect_error(river_floods(land, 10, 5, year_prob = NA), "`year_prob`")
  expect_error(river_floods(land, 10, 5, start = 6), "`start`")
})


test_that("simulate_evolving_metacommunity() checks its arguments", {
  ls <- landscape_implicit(4)
  anc <- data.frame(optimum = 50, sigma = 20, r_max = 5, row.names = "sp1")
  sc <- speciation_control("geographic", threshold = 10)
  run <- function(...) simulate_evolving_metacommunity(ls, anc, sc, n_steps = 2, ...)
  expect_error(simulate_evolving_metacommunity(list(), anc, sc), "`landscape`")
  expect_error(simulate_evolving_metacommunity(ls, anc, sc, n_steps = 0), "`n_steps`")
  expect_error(run(inter_max = -1), "`inter_max`")
  expect_error(run(inter_min = 2), "`inter_min`")
  expect_error(run(scale = 0), "`scale`")
  expect_error(run(distance_scale = 0), "`distance_scale`")
  expect_error(run(niche_overlap = NA), "`niche_overlap`")
  expect_error(run(max_species = 0), "`max_species`")
})

test_that("drift_test() checks its arguments", {
  set.seed(1)
  x <- matrix(rnorm(90), 30)
  g <- rep(1:5, each = 6)
  expect_error(drift_test(x, g, level = c(0.9, 0.95)), "`level`")
  expect_error(drift_test(x, g, level = 1), "`level`")
  expect_error(drift_test(x, g, correct = "yes"), "`correct`")
  x[1, 1] <- Inf
  expect_error(drift_test(x, g), "`x`")
  expect_error(drift_test(matrix(rnorm(90), 30), g, W = diag(c(1, NA, 1))), "`W`")
})

test_that("drift_test() regresses log variance among groups on log eigenvalues of W", {
  set.seed(1)
  G <- matrix(c(4, 1, 0.5, 0, 1, 3, 0.2, 0, 0.5, 0.2, 2, 0.3, 0, 0, 0.3, 1), 4)
  means <- matrix(rnorm(25 * 4), 25) %*% chol(G * 0.5)
  grp <- rep(seq_len(25), each = 10)
  ind <- means[grp, ] + matrix(rnorm(250 * 4), 250) %*% chol(G)
  colnames(ind) <- paste0("t", 1:4)
  test <- drift_test(ind, grp)
  expect_s3_class(test, "drift_test")
  # manual computation
  m <- rowsum(ind, grp) / 10
  W <- crossprod(ind - m[grp, ]) / (250 - 25)
  e <- eigen(W, symmetric = TRUE)
  b <- apply(m %*% e$vectors, 2, var)
  fit <- lm(log(b) ~ log(e$values))
  expect_equal(test$slope, unname(coef(fit)[2]))
  expect_equal(unname(test$W), unname(W))
  expect_equal(test$components$between, b)
  expect_equal(test$df, 2)
  expect_equal(test$p_value, 2 * pt(-abs((test$slope - 1) / test$se), 2))
  expect_true(test$conf_int[1] < test$slope && test$slope < test$conf_int[2])
  # data frames with a group column, and a known G
  df <- data.frame(site = grp, ind, label = "a")
  expect_equal(drift_test(df, "site")$slope, test$slope)
  expect_equal(drift_test(df, df$site, traits = paste0("t", 1:4))$slope, test$slope)
  known <- drift_test(ind, grp, W = G)
  expect_equal(unname(known$W), G)
  expect_output(print(known), "slope = 1")
  expect_s3_class(plot(known), "ggplot")
  # divergence only along the minor axis gives a slope below 1
  e <- eigen(G, symmetric = TRUE)
  minor <- outer(rnorm(25), e$vectors[, 4]) + matrix(rnorm(25 * 4, sd = 0.05), 25)
  expect_lt(drift_test(minor[grp, ] + 0, grp, W = G)$slope, 1)
})

test_that("drift_test() checks its input", {
  set.seed(2)
  x <- matrix(rnorm(60), 20)
  g <- rep(1:5, each = 4)
  expect_error(drift_test(x[, 1:2], g), "three traits")
  expect_error(drift_test(x, g[-1]), "one value per row")
  expect_error(drift_test(x, rep(1:2, each = 10)), "three groups")
  expect_error(drift_test(x, 1:20), "too few individuals")
  expect_error(drift_test(x, g, W = diag(2)), "symmetric")
  expect_error(drift_test(x, g, W = diag(c(1, 1, 0))), "positive definite")
  expect_error(drift_test(x, g, level = 2), "level")
  expect_error(drift_test(data.frame(x), g, traits = "z"), "name columns")
  expect_error(drift_test("a", g), "numeric matrix")
  expect_error(drift_test(cbind(1, 2, 3)[rep(1, 9), ], rep(1:3, 3), W = diag(3)), "do not vary")
  # column names are filled in when missing
  expect_identical(rownames(drift_test(x, g)$W), paste0("trait", 1:3))
})

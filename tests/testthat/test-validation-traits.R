  expect_error(trait_densities(d, bw = 0), "`bw`")
  expect_error(trait_densities(d, abundance = NA_character_), "`abundance`")
  skip_if_not_installed("ggplot2")
  expect_error(plot(res, hatch = NA), "`hatch`")
  expect_error(plot(res, hatch_density = 0), "`hatch_density`")
  expect_error(plot(res, point_size = -1), "`point_size`")
  expect_error(plot(res, interval_width = "2"), "`interval_width`")
  expect_error(plot(res, scales = 1), "`scales`")
  expect_error(plot_population_traits(d, alpha = 1.5), "`alpha`")
  expect_error(plot_population_traits(d, weighted = "yes"), "`weighted`")
  expect_error(plot_population_traits(d, community = NA), "`community`")

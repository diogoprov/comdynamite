# Checks of scalar arguments of the functions on traits and individuals: each bad value stops
# with a message that names the argument.

toy_individuals <- function() {
  set.seed(1)
  d <- data.frame(site = rep(paste0("s", 1:4), each = 20),
                  species = sample(c("a", "b", "c"), 80, replace = TRUE))
  d$trait <- c(a = 10, b = 14, c = 18)[d$species] + stats::rnorm(80)
  d$abundance <- 5
  d$env <- rep(1:4, each = 20)
  d
}
toy_tree <- ape::read.tree(text = "((a:1,b:1):1,(c:1.5,d:1.5):0.5);")

test_that("subsample_individuals() and trait_rarefaction() check their scalars", {
  d <- toy_individuals()
  expect_error(subsample_individuals(as.list(d)), "`individuals`")
  expect_error(subsample_individuals(d, n = c(2, 3)), "`n`")
  expect_error(subsample_individuals(d, n = 0), "`n`")
  expect_error(subsample_individuals(d, fraction = 0), "`fraction`")
  expect_error(subsample_individuals(d, fraction = NA_real_), "`fraction`")
  expect_error(subsample_individuals(d, cover = 1.2), "`cover`")
  expect_error(subsample_individuals(d, min_n = 1.5), "`min_n`")
  expect_error(subsample_individuals(d, site = c("site", "species")), "`site`")
  expect_error(subsample_individuals(d, species = NA_character_), "`species`")
  expect_error(subsample_individuals(d, abundance = 1), "`abundance`")
  # Inf keeps every individual, as NULL does
  expect_equal(subsample_individuals(d, n = Inf), d)
  expect_error(trait_rarefaction(d, reps = 0), "`reps`")
  expect_error(trait_rarefaction(d, level = 1), "`level`")
  expect_error(trait_rarefaction(d, min_n = "2"), "`min_n`")
  expect_error(trait_rarefaction(d, statistic = "mean"), "`statistic`")
  expect_error(trait_rarefaction(d, cover = c(0.5, NA)), "`cover`")
  expect_error(trait_rarefaction(d, site = 1), "`site`")
  rare <- trait_rarefaction(d, n = 2:3, reps = 2)
  skip_if_not_installed("ggplot2")
  expect_error(plot(rare, reference = "a"), "`reference`")
  expect_error(plot(rare, alpha = 2), "`alpha`")
  expect_error(plot(rare, scales = NA), "`scales`")
})


test_that("tstats(), trait_flex(), nested_variance() and community_index() check arguments", {
  d <- toy_individuals()
  expect_error(tstats(as.matrix(d)), "`individuals`")
  expect_error(tstats(d, traits = character(0)), "`traits`")
  expect_error(tstats(d, site = c("a", "b")), "`site`")
  expect_error(tstats(d, n_perm = 1.5), "`n_perm`")
  expect_error(tstats(d, traits = NA_character_), "`traits`")
  expect_error(trait_flex(d, traits = 1), "`traits`")
  expect_error(trait_flex(d, species = TRUE), "`species`")
  expect_error(trait_flex(d, abundance = c("a", "b")), "`abundance`")
  expect_error(trait_flex(d, formula = trait ~ env), "`formula`")
  expect_error(trait_flex(d, formula = "~ env"), "`formula`")
  expect_error(nested_variance(as.list(d), "trait", "site"), "`data`")
  expect_error(nested_variance(d, "trait", character(0)), "`factors`")
  expect_error(nested_variance(d, 1, "site"), "`traits`")
  expect_error(nested_variance(d, "trait", "site", crossed = 1), "`crossed`")
  expect_error(nested_variance(d, "trait", "site", crossed = "species", interaction = NA),
               "`interaction`")
  expect_error(community_index(d, stats::var, multivariate = "yes"), "`multivariate`")
  expect_error(community_index(d, stats::var, n_perm = -1), "`n_perm`")
  expect_error(community_index(d, stats::var, species = 2), "`species`")
})

test_that("summaries and plots of null-model tests check their scalars", {

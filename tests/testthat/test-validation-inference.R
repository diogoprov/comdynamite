# Checks of the scalar arguments of the functions of inference (rOpenSci G2.0-G2.2, G2.16)

test_that("abc_table() and run_scenarios() check their scalar arguments", {
  prior <- list(a = c(0, 1))
  f <- function(scenario, shared) 1
  expect_error(abc_table(prior, "f", 2), "`simulate`")
  expect_error(abc_table(prior, f, 2, setup = 1), "`setup`")
  expect_error(abc_table(prior, f, 2, summarise = NULL), "`summarise`")
  expect_error(abc_table(prior, f, c(2, 3)), "`n`")
  expect_error(abc_table(prior, f, 0), "`n`")
  expect_error(abc_table(prior, f, 2, seed = NA), "`seed`")
  expect_error(abc_table(prior, f, 2, seed = 1.5), "`seed`")
  grid <- data.frame(a = 1:2)
  expect_error(run_scenarios(list(a = 1), f), "`scenarios`")
  expect_error(run_scenarios(grid[0, , drop = FALSE], f), "`scenarios`")
  expect_error(run_scenarios(grid, f, n_rep = 0), "`n_rep`")
  expect_error(run_scenarios(grid, f, n_rep = NA), "`n_rep`")
  expect_error(run_scenarios(grid, f, seed = "a"), "`seed`")
  expect_error(run_scenarios(grid, f, seed = Inf), "`seed`")
})

test_that("functions of ABC check their scalar arguments before fitting", {
  table <- data.frame(a = seq(0, 1, length.out = 30), s1 = seq(0, 1, length.out = 30))
  expect_error(abc_fit(as.list(table), "a"), "`table`")
  expect_error(abc_fit(table, "a", ntree = 0), "`ntree`")
  expect_error(abc_fit(table, "a", ncores = "2"), "`ncores`")
  expect_error(abc_recovery(table, "a", n_test = 1), "`n_test`")
  expect_error(abc_recovery(table, "a", n_test = 25), "`n_test`")
  expect_error(abc_recovery(table, "a", n_test = 5, level = 1), "`level`")
  expect_error(abc_recovery(table, "a", n_test = 5, ntree = c(1, 2)), "`ntree`")
  expect_error(abc_recovery(table, "a", n_test = 5, seed = NA), "`seed`")
  expect_error(abc_choose(list(x = table, y = table), ntree = -1), "`ntree`")
  expect_error(abc_choose(list(x = table, y = table), lda = NA), "`lda`")
  expect_error(abc_choose(list(x = table, y = table), ncores = 0), "`ncores`")
  expect_error(abc_importance(table), "`x`")
  expect_error(abc_ppc(table, c(s1 = 1), table), "`fit`")
  expect_error(abc_diagnose(list(), c(s1 = 1)), "`fit`")
  expect_error(abc_cv(as.list(table), c(s1 = 1)), "`table`")
  expect_error(abc_cv(table, c(s1 = 1), "a", level = NA), "`level`")
  expect_error(abc_cv(table, c(s1 = 1), "a", n = 1), "`n`")
  expect_error(abc_cv(table, c(s1 = 1), "a", ntree = 1.5), "`ntree`")
  expect_error(abc_cv(table, c(s1 = 1), "a", ncores = Inf), "`ncores`")
  expect_error(abc_cv(table, c(s1 = 1), "a", seed = c(1, 2)), "`seed`")
  fit <- structure(list(), class = "mc_abc_fit")
  expect_error(predict(fit, c(s1 = 1), level = 0), "`level`")
  expect_error(predict(fit, c(s1 = 1), ncores = 0), "`ncores`")
  expect_error(abc_ppc(fit, c(s1 = 1), as.list(table)), "`table`")
  expect_error(abc_ppc(fit, c(s1 = 1), table, n = 1), "`n`")
  expect_error(abc_ppc(fit, c(s1 = 1), table, simulate = 1), "`simulate`")
  expect_error(abc_ppc(fit, c(s1 = 1), table, seed = "1"), "`seed`")
  expect_error(abc_diagnose(fit, c(s1 = 1), coverage = c(0.5, 0.9)), "`coverage`")
  expect_error(abc_diagnose(fit, c(s1 = 1), coverage = NaN), "`coverage`")
  choice <- structure(list(), class = "mc_abc_choice")
  expect_error(predict(choice, c(s1 = 1), ntree = 0), "`ntree`")
  expect_error(predict(choice, c(s1 = 1), ncores = NA), "`ncores`")
})

test_that("spatial_folds() and fold_summarise() check their arguments", {
  coords <- expand.grid(x = 1:4, y = 1:4)
  expect_error(spatial_folds(coords, k = 1), "`k`")
  expect_error(spatial_folds(coords, k = 17), "`k`")
  expect_error(spatial_folds(coords, k = NA), "`k`")
  expect_error(spatial_folds(coords, seed = "a"), "`seed`")
  expect_error(spatial_folds(letters[1:4]), "`coords`")
  bad <- coords
  bad$x[1] <- NA
  expect_error(spatial_folds(bad), "`coords`")
  expect_error(fold_summarise(c(1, 2, NA)), "`folds`")
  expect_error(fold_summarise(c("a", "b")), "`folds`")
  expect_error(fold_summarise(c(1, 2), summarise = 1), "`summarise`")
  expect_type(fold_summarise(factor(c("a", "b"))), "closure")
})

test_that("DAMOCLES functions check their scalar arguments", {
  tree <- ape::read.tree(text = "((a:1,b:1):1,(c:1,d:1):1);")
  comm <- matrix(c(1, 0, 1, 0), 1, dimnames = list(NULL, c("a", "b", "c", "d")))
  expect_error(simulate_damocles(tree, 1, 1, n = NA), "`n`")
  expect_error(simulate_damocles(tree, 1, 1, n = c(1, 2)), "`n`")
  expect_error(damocles_fit(comm, tree, shared = "yes"), "`shared`")
  expect_error(damocles_test(comm, tree, n_sim = 1.5), "`n_sim`")
  expect_error(damocles_test(comm, tree, shared = NA), "`shared`")
  expect_error(damocles_samples(comm, tree, regimes = list(1), cores = NA), "`cores`")
  reg <- clade_regimes(tree, list(A = c("a", "b")))
  expect_error(damocles_partition_test(comm, tree, reg, n_rand = NA), "`n_rand`")
  expect_error(damocles_partition_test(comm, tree, reg, n_boot = "1"), "`n_boot`")
  expect_error(damocles_partition_test(comm, tree, reg, tolerance = 0.5), "`tolerance`")
  expect_error(damocles_partition_test(comm, tree, reg, max_overlap = NA), "`max_overlap`")
  expect_error(damocles_partition_test(comm, tree, reg, cores = 0), "`cores`")
  expect_error(random_regimes(tree, reg, tolerance = Inf), "`tolerance`")
  expect_error(random_regimes(tree, reg, max_overlap = c(0.1, 0.2)), "`max_overlap`")
  expect_error(clade_regimes(tree, list(A = "a"), background = NA), "`background`")
  expect_error(clade_regimes(tree, list(A = "a"), background = 1), "`background`")
  expect_error(clade_regimes(tree, list(A = "a"), stem = NA), "`stem`")
  fit <- structure(data.frame(), class = c("mc_damocles_fit", "data.frame"))
  expect_error(confint(fit, level = NA), "`level`")
  expect_error(confint(fit, level = c(0.9, 0.95)), "`level`")
  expect_error(dr_rates(ape::read.tree(text = "(a:1,b:-1);")), "branch lengths")
})


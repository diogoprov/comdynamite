tree <- ape::read.tree(text = "((a:1,b:1):2,(c:2,(d:1,e:1):1):1);")

test_that("external traits replace one trait and leave the others as drawn", {
  set.seed(1)
  drawn <- species_traits(tree)
  optima <- c(e = 5, d = 4, c = 3, b = 2, a = 1)
  set.seed(1)
  out <- species_traits(tree, optima = optima)
  expect_equal(out$optimum, c(0, 25, 50, 75, 100))
  expect_equal(out[c("sigma", "r_max")], drawn[c("sigma", "r_max")])
  set.seed(1)
  raw <- species_traits(tree, optima = optima, rescale_optima = FALSE)
  expect_equal(raw$optimum, 1:5)
  set.seed(1)
  ranked <- species_traits(tree, optima = c(1, 10, 100, 1000, 10000), uniform_optima = TRUE)
  expect_equal(ranked$optimum, c(0, 25, 50, 75, 100))
  set.seed(1)
  both <- species_traits(tree, sigma = matrix(1:5, dimnames = list(letters[5:1], NULL)),
                         r_max = data.frame(r = c(2, 2, 3, 3, 4)))
  expect_equal(both$sigma, 5:1)
  expect_equal(both$r_max, c(2, 2, 3, 3, 4))
  expect_equal(both$optimum, drawn$optimum)
  expect_identical(attr(both, "tree"), tree)
  set.seed(2)
  unnamed <- species_traits(3, sigma = c(1, 2, 3))
  expect_equal(unnamed$sigma, 1:3)
})

test_that("wrong external traits stop", {
  expect_error(species_traits(tree, optima = 1:3), "3 values")
  expect_error(species_traits(tree, optima = c(a = 1, b = 2)), "no value for c, d, e")
  expect_error(species_traits(tree, optima = c(1, NA, 3, 4, 5)), "without NA")
  expect_error(species_traits(tree, optima = letters[1:5]), "numbers")
  expect_error(species_traits(tree, optima = matrix(1:10, 5)), "one column")
  expect_error(species_traits(tree, sigma = c(1, 0, 1, 1, 1)), "positive")
  expect_error(species_traits(tree, r_max = c(1, -1, 1, 1, 1)), "negative")
})
